`timescale 1ns/1ps

module tb_lock_controller;

    reg clk;
    reg rst;
    reg [3:0] digit_in;
    wire unlocked_led;

    // Підключення контролера
    lock_controller uut (
        .clk(clk),
        .rst(rst),
        .digit_in(digit_in),
        .unlocked_led(unlocked_led)
    );

    // Генератор тактового сигналу
    always #5 clk = ~clk;

    // Процедура перевірки стану
    task check_led;
        input expected;
        begin
            #1;
            if (unlocked_led !== expected)
                $display("ERROR: expected LED=%b, got LED=%b",
                         expected, unlocked_led);
            else
                $display("OK: LED=%b", unlocked_led);
        end
    endtask

    initial begin

        // Початкові значення
        clk = 0;
        rst = 1;
        digit_in = 4'd0;

        // Асинхронний reset
        #12;
        rst = 0;

        // ------------------------------------------------
        // 1. LOCKED -> WAIT_D2
        // Правильна перша цифра: 5
        // ------------------------------------------------
        digit_in = 4'd5;
        #10;
        check_led(1'b0);

        // ------------------------------------------------
        // 2. WAIT_D2 -> WAIT_D3
        // Правильна друга цифра: 3
        // ------------------------------------------------
        digit_in = 4'd3;
        #10;
        check_led(1'b0);

        // ------------------------------------------------
        // 3. WAIT_D3 -> UNLOCKED
        // Правильна третя цифра: 7
        // ------------------------------------------------
        digit_in = 4'd7;
        #10;
        check_led(1'b1);

        // ------------------------------------------------
        // UNLOCKED повинен залишатися UNLOCKED
        // ------------------------------------------------
        digit_in = 4'd1;
        #10;
        check_led(1'b1);

        // ------------------------------------------------
        // RESET -> LOCKED
        // ------------------------------------------------
        rst = 1;
        #2;
        check_led(1'b0);

        rst = 0;

        // ------------------------------------------------
        // ПОМИЛКА на першому кроці
        // ------------------------------------------------
        digit_in = 4'd2;
        #10;
        check_led(1'b0);

        // ------------------------------------------------
        // Починаємо правильну послідовність
        // ------------------------------------------------
        digit_in = 4'd5;
        #10;
        check_led(1'b0);

        // ------------------------------------------------
        // ПОМИЛКА на другому кроці
        // Очікується 3, подаємо 4
        // ------------------------------------------------
        digit_in = 4'd4;
        #10;
        check_led(1'b0);

        // ------------------------------------------------
        // Знову правильна перша цифра
        // ------------------------------------------------
        digit_in = 4'd5;
        #10;
        check_led(1'b0);

        // ------------------------------------------------
        // Правильна друга цифра
        // ------------------------------------------------
        digit_in = 4'd3;
        #10;
        check_led(1'b0);

        // ------------------------------------------------
        // ПОМИЛКА на третьому кроці
        // Очікується 7, подаємо 8
        // ------------------------------------------------
        digit_in = 4'd8;
        #10;
        check_led(1'b0);

        $display("--------------------------------");
        $display("TESTBENCH FINISHED");
        $display("--------------------------------");

        $finish;
    end

endmodule
